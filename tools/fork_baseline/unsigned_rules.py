"""Reviewed, build-local provisioning compatibility for an unsigned device package.

The original Apache-2.0 rules_apple sources and their gitlink remain untouched.
No profiles, identities, keys or application code are generated by this module.
"""
import hashlib
import os
from pathlib import Path, PurePosixPath
import subprocess

PINNED_COMMIT = "485016eb5b0948cc17307064e7977a6d68e94046"
SOURCES = {
    "apple/internal/ios_rules.bzl": ("b6776b1c10a2c965f01259dd95ebe1b045afc5e22b3446b8ae81d44f11c3a7da", 6),
    "apple/internal/watchos_rules.bzl": ("4c9c5a50489d25ab6b0bbdc1e3bd40ef0320c31ba00d54ef53ff50fb3dddac12", 3),
}
BEFORE = "    if platform_prerequisites.platform.is_device:\n        processor_partials.append(\n            partials.provisioning_profile_partial("
AFTER = "    if (platform_prerequisites.platform.is_device and\n        \"ayugram.unsigned_device\" not in platform_prerequisites.features):\n        processor_partials.append(\n            partials.provisioning_profile_partial("


def patch_source(data, expected_sha, expected_count):
    if hashlib.sha256(data).hexdigest() != expected_sha:
        raise ValueError("Unsigned rules input does not match reviewed source")
    text = data.decode("utf-8")
    if text.count(BEFORE) != expected_count:
        raise ValueError("Unsigned rules patch sites changed")
    return text.replace(BEFORE, AFTER).encode("utf-8")


def prepare_unsigned_rules(source, destination):
    source, destination = Path(source).resolve(strict=True), Path(destination)
    def git(*args):
        return subprocess.check_output(["git", "-C", str(source), *args], stderr=subprocess.DEVNULL)
    if git("rev-parse", "HEAD").decode().strip() != PINNED_COMMIT:
        raise ValueError("Unsigned rules repository is not the reviewed commit")
    if destination.exists() or destination.is_symlink():
        raise ValueError("Unsigned rules destination must be fresh")
    entries = git("ls-tree", "-r", "-z", "HEAD").split(b"\0")
    destination.mkdir(mode=0o700)
    copied = set()
    for entry in entries:
        if not entry:
            continue
        metadata, raw_path = entry.split(b"\t", 1)
        mode, kind, oid = metadata.decode().split()
        relative = PurePosixPath(raw_path.decode("utf-8"))
        if kind != "blob" or mode not in {"100644", "100755", "120000"} or relative.is_absolute() or ".." in relative.parts:
            raise ValueError("Unsupported unsigned rules source entry")
        original = source.joinpath(*relative.parts)
        if mode == "120000":
            if not original.is_symlink() or not original.resolve(strict=True).is_relative_to(source):
                raise ValueError("Unsigned rules symlink escapes reviewed source")
            data = os.readlink(original).encode("utf-8")
        else:
            if original.is_symlink() or not original.is_file():
                raise ValueError("Unsigned rules input is not a regular file")
            data = original.read_bytes()
        blob = b"blob " + str(len(data)).encode() + b"\0" + data
        if hashlib.sha1(blob).hexdigest() != oid:
            raise ValueError("Unsigned rules working files differ from their pinned tree")
        target = destination.joinpath(*relative.parts)
        target.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        if mode == "120000":
            target.symlink_to(os.readlink(original))
        else:
            with target.open("xb") as stream:
                stream.write(data)
            target.chmod(0o700 if mode == "100755" else 0o600)
        copied.add(str(relative))
    changes = {}
    for path, (digest, count) in SOURCES.items():
        if path not in copied:
            raise ValueError("Unsigned rules source file is missing")
        file = destination / path
        if file.is_symlink() or not file.is_file():
            raise ValueError("Unsigned patch target must be a regular file")
        patched = patch_source(file.read_bytes(), digest, count)
        file.write_bytes(patched)
        changes[path] = {"original_sha256": digest, "patched_sha256": hashlib.sha256(patched).hexdigest(), "sites": count}
    return {"source_commit": PINNED_COMMIT, "feature": "ayugram.unsigned_device", "signed_builds_affected": False, "files": changes}
